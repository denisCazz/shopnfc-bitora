function normalizeProvinceKey(value: string): string {
  return value
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/citt[aà] metropolitana di /g, "")
    .replace(/provincia autonoma di /g, "")
    .replace(/provincia di /g, "")
    .replace(/['’]/g, "")
    .replace(/[^a-z0-9]+/g, " ")
    .trim();
}

export function italianProvinceCode(
  county?: string | null,
  state?: string | null
): string {
  for (const raw of [county, state]) {
    if (!raw) continue;
    const trimmed = raw.trim();
    if (/^[A-Z]{2}$/i.test(trimmed)) return trimmed.toUpperCase();
    const key = normalizeProvinceKey(trimmed);
    if (PROVINCE_NAMES[key]) return PROVINCE_NAMES[key];
  }
  return "";
}
